import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
// Litepod selects a Dockerfile path. Derive standalone stages to prevent drift.
const root = readFileSync('Dockerfile', 'utf8').replaceAll('\r\n', '\n');
const worker = root.split('\nFROM runtime AS app\n')[0];
if (!worker.includes('FROM runtime AS worker')) throw Error('Worker stage missing');
const qris = readFileSync('integrations/qris/Dockerfile', 'utf8')
  .replaceAll('\r\n', '\n')
  .replace('COPY requirements.txt', 'COPY integrations/qris/requirements.txt')
  .replace('COPY --chown=qris:qris vendor', 'COPY --chown=qris:qris integrations/qris/vendor')
  .replace(
    'COPY --chown=qris:qris worker.py health_http.py test_worker.py vendor-manifest.json',
    'COPY --chown=qris:qris integrations/qris/worker.py integrations/qris/health_http.py integrations/qris/test_worker.py integrations/qris/vendor-manifest.json',
  );
for (const [file, source] of Object.entries({
  'deploy/litepod/worker.Dockerfile': worker,
  'deploy/litepod/qris.Dockerfile': qris,
})) {
  const expected =
    '# Generated by node scripts/generate-litepod-dockerfiles.mjs; build context: repository root.\n' +
    source.trimEnd() +
    '\n';
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== expected)
      throw Error('Regenerate ' + file);
  } else {
    mkdirSync('deploy/litepod', { recursive: true });
    writeFileSync(file, expected);
  }
  console.log(file);
}
